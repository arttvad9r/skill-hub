#!/usr/bin/env python3
from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROFILES = ROOT / "profiles"
CATALOG = ROOT / "catalog.toml"
OUTPUT = ROOT / "CATALOG.md"


def load_toml(path: Path) -> dict:
    with path.open("rb") as fh:
        return tomllib.load(fh)


def resolve_profile(name: str, stack: tuple[str, ...] = ()) -> list[str]:
    if name in stack:
        raise ValueError("profile cycle: " + " -> ".join((*stack, name)))
    data = load_toml(PROFILES / f"{name}.toml")
    result: list[str] = []
    for parent in data.get("extends", []):
        result.extend(resolve_profile(parent, (*stack, name)))
    result.extend(data.get("skills", []))
    return list(dict.fromkeys(result))


def family(name: str) -> str:
    if name.startswith("android-"):
        return "Android"
    if name == "mobile-accessibility":
        return "Accessibility"
    if name.startswith("design"):
        return "Design"
    if name.startswith("game-"):
        return "Game development"
    if name.startswith("security-"):
        return "Security"
    if name.startswith("docker-") or name == "fastapi":
        return "Infrastructure / backend"
    return "Other"


def esc(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def render() -> str:
    cat = load_toml(CATALOG)["skills"]
    profile_rows: list[tuple[str, str, str, list[str]]] = []
    for path in sorted(PROFILES.glob("*.toml")):
        data = load_toml(path)
        profile_rows.append((family(path.stem), path.stem, data.get("description", ""), resolve_profile(path.stem)))

    lines = [
        "# Skill Hub catalog",
        "",
        "Browse the curated profiles and vendored/project-owned skills without cloning the repository.",
        "",
        f"Current catalog: **{len(cat)} skills across {len(profile_rows)} profiles**.",
        "",
        "> Generated by `python3 tools/render_catalog.py`. Do not edit this file by hand.",
        "",
        "## Profiles",
        "",
        "Profiles are the preferred install unit. They resolve inheritance and install the smallest curated capability pack for a project or task.",
        "",
    ]

    current = None
    for fam, name, description, skills in profile_rows:
        if fam != current:
            if current is not None:
                lines.append("")
            lines.extend([
                f"### {fam}",
                "",
                "| Profile | Description | Resolved skills |",
                "| --- | --- | ---: |",
            ])
            current = fam
        lines.append(f"| [`{name}`](profiles/{name}.toml) | {esc(description)} | {len(skills)} |")

    lines.extend([
        "",
        "## Skills",
        "",
        "Each skill records its source, pinned revision, category, and license in `catalog.toml`. Project-owned skills are covered by the repository's Apache-2.0 license; vendored skills keep their upstream license.",
        "",
        "| Skill | Category | Source | Revision | License |",
        "| --- | --- | --- | --- | --- |",
    ])
    for name in sorted(cat):
        meta = cat[name]
        revision = meta.get("revision", "")
        short_revision = revision[:12] if len(str(revision)) > 16 and all(c in "0123456789abcdef" for c in str(revision).lower()) else revision
        source = esc(meta.get("source", ""))
        source_url = str(meta.get("source_url", ""))
        source_cell = f"[{source}]({source_url})" if source_url.startswith(("https://", "http://")) else source
        license_name = esc(meta.get("license", ""))
        license_file = str(meta.get("license_file", ""))
        license_cell = f"[{license_name}]({license_file})" if license_file else license_name
        lines.append(
            f"| [`{name}`](skills/{name}/) | {esc(meta.get('category', ''))} | {source_cell} | `{esc(short_revision)}` | {license_cell} |"
        )

    lines.extend([
        "",
        "## Browse from the CLI",
        "",
        "```bash",
        "skillhub profiles",
        "skillhub show android-compose-app",
        "skillhub show design-web",
        "```",
        "",
        "For third-party attribution and full upstream license locations, see [THIRD_PARTY.md](THIRD_PARTY.md).",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Render CATALOG.md from catalog.toml and profiles/*.toml")
    parser.add_argument("--check", action="store_true", help="Exit non-zero if CATALOG.md is stale")
    args = parser.parse_args()
    expected = render()
    if args.check:
        actual = OUTPUT.read_text() if OUTPUT.exists() else ""
        if actual != expected:
            print("CATALOG.md is stale; run `python3 tools/render_catalog.py`", file=sys.stderr)
            return 1
        print("CATALOG.md is current")
        return 0
    OUTPUT.write_text(expected)
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
